function _mergeSetData(a: SetData, b: SetData): SetData {
	const map = new Map<string, Question[]>();
	for (const st of a.subtopics) map.set(st.name, [...st.questions]);
	for (const st of b.subtopics) {
		const ex = map.get(st.name) || [];
		map.set(st.name, [...ex, ...st.questions]);
	}
	return {
		subtopics: _bondingOrder
			.map(name => ({ name, questions: map.get(name) || [] }))
			.filter(st => st.questions.length > 0),
	};
}

